import { describe, expect, it } from "vitest";

import {
  assertAdapterMessage,
  assertCoreMessage,
  SCHEMA_SHA256,
} from "../src/contract.js";

describe("generated relay contract", () => {
  it("accepts protocol messages generated by the adapter", () => {
    expect(() =>
      assertAdapterMessage({ type: "shutdown", protocol_version: "1" }),
    ).not.toThrow();
  });

  it("rejects extra fields", () => {
    expect(() =>
      assertAdapterMessage({
        type: "shutdown",
        protocol_version: "1",
        extra: true,
      }),
    ).toThrow();
  });

  it("accepts the core handshake and exposes a SHA-256 digest", () => {
    expect(() =>
      assertCoreMessage({
        type: "ready",
        protocol_version: "1",
        schema_sha256: SCHEMA_SHA256,
        core_version: "0.2.0",
      }),
    ).not.toThrow();
    expect(SCHEMA_SHA256).toMatch(/^[a-f0-9]{64}$/u);
  });
});
